/*
  The full varlock runtime initialization sequence, as one function.

  Every init path (the `varlock/auto-init` entry, the self-contained `varlock/init-bundle`
  CJS file injected by the Next.js integration, the virtual init module generated by the
  vite integration, the Cloudflare init entry) runs exactly this. It must stay evaluable in
  edge runtimes: nothing in here (or in what it imports) may touch node builtins at module
  scope.

  Importing this module (`varlock/init`) has NO side effects; `varlock/auto-init` is the
  entry that runs it on import. Which one to use is decided by ESM import hoisting:

  - Code that imports it as a dependency (an app's entry file) must use `varlock/auto-init`.
    Every static import in that file is hoisted above its body, so a call placed after the
    imports would run after sibling modules that already read `ENV` at module scope. Only an
    earlier static import evaluates before them.
  - Code that generates the importing module itself (the vite integration's virtual init
    module, the Cloudflare init entry) calls `initVarlockRuntime()` instead, because it has
    to run its own body first (bake in a resolved env, load Cloudflare bindings), and no
    import, side-effect or not, can be ordered after that body.
*/

import { initVarlockEnv } from './env';
import { patchGlobalConsole } from './patch-console';
import { patchProcessStreams } from './patch-process-streams';
import { patchGlobalServerResponse } from './patch-server-response';
import { patchGlobalResponse } from './patch-response';
import { isEncryptedBlob, decryptEnvBlobSync, decryptEnvBlobAsync } from './crypto';

function initNow() {
  initVarlockEnv();
  // each of these is a no-op where it does not apply (disabled by settings, or the runtime
  // has no process streams / no node:http)
  patchGlobalConsole();
  patchProcessStreams();
  patchGlobalServerResponse();
  patchGlobalResponse();
}

/**
 * Gate Next.js edge handler invocation until `ready` resolves.
 *
 * The injected edge bundle runs at the very top of the edge runtime file, BEFORE the
 * bundler code registers handlers on `globalThis._ENTRIES`, so we install a Proxy
 * that wraps everything subsequently registered. Two registration shapes exist:
 *  - turbopack: `_ENTRIES.middleware_x = <thenable proxy>` - the platform awaits
 *    the entry, so we chain that await behind `ready`
 *  - webpack: `_ENTRIES.middleware_x = { default: handler }` - the platform calls
 *    function properties directly, so we wrap them to await `ready` first
 */
function gateEdgeEntriesUntilReady(ready: Promise<void>) {
  const wrapEntry = (entry: any) => {
    if (!entry || (typeof entry !== 'object' && typeof entry !== 'function')) return entry;
    return new Proxy(entry, {
      get(target, prop, receiver) {
        if (prop === 'then' && typeof (target as any).then === 'function') {
          // thenable entry - resolve to the real entry only once env is ready
          // (promise assimilation then awaits the underlying entry itself)
          const chained = ready.then(() => target);
          return chained.then.bind(chained);
        }
        const val = Reflect.get(target, prop, receiver);
        if (typeof val === 'function' && prop !== 'then') {
          return async function gatedEdgeHandler(...args: Array<any>) {
            await ready;
            return val.apply(target, args);
          };
        }
        return val;
      },
    });
  };

  const store: Record<string, any> = {};
  const existing = (globalThis as any)._ENTRIES;
  if (existing) {
    for (const key of Object.keys(existing)) store[key] = wrapEntry(existing[key]);
  }
  const entriesProxy = new Proxy(store, {
    set(target, prop, value) {
      target[prop as string] = wrapEntry(value);
      return true;
    },
  });
  // accessor (not a plain value) because bundler wrappers do
  // `self._ENTRIES = self._ENTRIES || {}` - an assignment even when already set,
  // which would throw on a non-writable property in strict mode. Reassignments
  // funnel their entries through the wrapping proxy instead.
  Object.defineProperty(globalThis, '_ENTRIES', {
    configurable: true,
    get: () => entriesProxy,
    set: (v) => {
      if (v && v !== entriesProxy) {
        for (const key of Object.keys(v)) (entriesProxy as any)[key] = v[key];
      }
    },
  });
}

/**
 * Finds the encrypted env blob this process was handed, if any. Two channels:
 *  - `globalThis.__varlockEncryptedEnv`: set by code that runs ahead of init in the same
 *    bundle (the vite integration's `resolved-env` mode, the Cloudflare bindings loader)
 *  - `process.env.__VARLOCK_ENV`: injected by the platform / a parent process
 */
function getEncryptedEnvBlob(): { blob: string, source: 'global' | 'process' } | undefined {
  const globalBlob = (globalThis as any).__varlockEncryptedEnv;
  if (typeof globalBlob === 'string' && globalBlob) return { blob: globalBlob, source: 'global' };
  const processBlob = (globalThis as any).process?.env?.__VARLOCK_ENV;
  if (typeof processBlob === 'string' && isEncryptedBlob(processBlob)) return { blob: processBlob, source: 'process' };
  return undefined;
}

function storeDecryptedEnv(decrypted: string, source: 'global' | 'process') {
  if (source === 'global') {
    (globalThis as any).__varlockLoadedEnv = JSON.parse(decrypted);
    delete (globalThis as any).__varlockEncryptedEnv;
  } else {
    process.env.__VARLOCK_ENV = decrypted;
  }
}

/**
 * Initializes the varlock runtime: decrypts an encrypted env blob when one is present
 * (using `_VARLOCK_ENV_KEY`), loads the resolved env into `ENV` / `process.env`, and
 * applies the console, process stream, ServerResponse and Response patches.
 *
 * Safe to call more than once - every step is idempotent.
 *
 * Decryption is synchronous wherever node:crypto exists (node, Cloudflare with
 * nodejs_compat, Next's local edge sandbox). Runtimes without it (e.g. Vercel Edge) fall
 * back to async Web Crypto: env init then completes in a microtask, the promise is exposed
 * as `globalThis.__varlockEnvReady`, and Next.js edge handler invocation is gated on it.
 */
export function initVarlockRuntime() {
  const encrypted = getEncryptedEnvBlob();
  if (encrypted) {
    const key = (globalThis as any).process?.env?._VARLOCK_ENV_KEY;
    if (!key) throw new Error('[varlock] env blob is encrypted but _VARLOCK_ENV_KEY is not set');
    try {
      storeDecryptedEnv(decryptEnvBlobSync(encrypted.blob, key), encrypted.source);
      initNow();
    } catch (err) {
      // only fall back for the "runtime has no node:crypto" case - anything else
      // (bad key, corrupt blob) should fail loudly right here
      if (!String((err as Error).message).includes('node:crypto is not available')) throw err;
      const ready = decryptEnvBlobAsync(encrypted.blob, key).then((decrypted) => {
        // hand the decrypted graph to initVarlockEnv via its globalThis input
        // channel - process.env is read-only in some edge runtimes (e.g. Vercel),
        // so writing the decrypted blob back would silently no-op
        (globalThis as any).__varlockLoadedEnv = JSON.parse(decrypted);
        delete (globalThis as any).__varlockEncryptedEnv;
        try {
          process.env.__VARLOCK_ENV = decrypted;
        } catch { /* frozen process.env - the globalThis channel covers init */ }
        initNow();
      });
      // mark rejections handled so a bad key / corrupt blob doesn't surface as an
      // unhandled rejection (fatal on some edge runtimes) before any request runs -
      // gated handlers still await `ready` and surface the real error per-request
      // eslint-disable-next-line @typescript-eslint/no-empty-function
      ready.catch(() => {});
      (globalThis as any).__varlockEnvReady = ready;
      gateEdgeEntriesUntilReady(ready);
    }
  } else {
    initNow();
  }

  // Expose on globalThis so downstream code (e.g. webpack loaders, the vite integration's
  // dev transform) can re-patch the console without require() - needed in edge sandboxes
  // that can't resolve bare requires, and after React's dev RSC console replay wraps it.
  (globalThis as any).__varlockPatchConsole = patchGlobalConsole;
}
