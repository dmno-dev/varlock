import { createHash } from 'node:crypto';

import { getAutogeneratedBanner } from '../banners';
import {
  getFieldDocLines,
  getSensitiveKeys,
  type ResolvedFieldType,
} from '../shared';
import { generateCsharpEnvSrc, snakeToPascalCase } from './csharp';

/** `Verb-Noun` function name, e.g. `Get-AppEnv` */
const PWSH_FUNCTION_NAME = /^[A-Za-z][A-Za-z0-9]*-[A-Za-z][A-Za-z0-9]*$/;

const PWSH_DOCS_URL = 'https://varlock.dev/integrations/powershell/';

/** Single-quoted PowerShell literal. Doubles the quote characters PowerShell accepts as quotes. */
function pwshStringLiteral(text: string): string {
  return `'${text.replace(/['\u2018\u2019\u201A\u201B]/g, (ch) => ch + ch)}'`;
}

/**
 * The PowerShell name for a generated C# property type. Read from the generated source, so the help
 * can't disagree with the class. `string?` and `object?` are shown without the `?`, as the reference
 * types they are.
 */
function psTypeName(csharpType: string): string {
  const nullable = csharpType.endsWith('?');
  const base = nullable ? csharpType.slice(0, -1) : csharpType;
  if (base === 'string' || base === 'object') return base;
  const names: Record<string, string> = {
    long: 'long', double: 'double', bool: 'bool', JsonElement: 'JsonElement',
  };
  const name = names[base] ?? base;
  return nullable ? `${name}?` : name;
}

/** Each property's C# type, keyed by property name, read from the `{ get; init; }` declarations. */
function csharpPropertyTypes(csharpSrc: string): Map<string, string> {
  const types = new Map<string, string>();
  for (const match of csharpSrc.matchAll(/^\s*public (?:required )?(\S+) ([A-Za-z_][A-Za-z0-9_]*) \{ get; init; \}\s*$/gm)) {
    types.set(match[2], match[1]);
  }
  return types;
}


/**
 * Comment-based help for the generated function, with a section per help tier:
 * SYNOPSIS and DESCRIPTION (default), EXAMPLE (-Examples), and INPUTS, OUTPUTS, NOTES, and LINK (-Full).
 * `#>` in generated text is neutralized so it can't end the comment block early.
 */
function helpLines(
  functionName: string,
  typeFullName: string,
  properties: Array<{ field: ResolvedFieldType, prop: string, type: string }>,
): Array<string> {
  const safeLine = (line: string) => line.replace(/#>/g, '# >');
  const nameWidth = Math.max(0, ...properties.map(({ prop }) => prop.length));
  const typeWidth = Math.max(0, ...properties.map(({ type }) => type.length));
  const propertyLines = properties.map(({ field, prop, type }) => {
    const docs = getFieldDocLines(field).join(' ');
    const sensitive = field.isSensitive ? ' (sensitive)' : '';
    return safeLine(`  ${prop.padEnd(nameWidth)}  ${type.padEnd(typeWidth)}  ${docs}${sensitive}`.trimEnd());
  });
  const [first, second] = properties;

  const examples: Array<string> = [
    '.EXAMPLE',
    `${functionName}`,
    '',
    'Returns the whole object, with one property per schema item.',
    '',
  ];
  if (first) {
    examples.push(
      '.EXAMPLE',
      `(${functionName}).${first.prop}`,
      '',
      'Reads a single value. The result has the type shown under Properties.',
      '',
    );
  }
  if (first && second) {
    examples.push(
      '.EXAMPLE',
      `${functionName} | Select-Object ${first.prop}, ${second.prop}`,
      '',
      'Selects several values from the object.',
      '',
    );
  }
  examples.push(
    '.EXAMPLE',
    `try { ${functionName} } catch { Write-Error $_.Exception.Message }`,
    '',
    'Handles a missing __VARLOCK_ENV or a missing required key without stopping the script.',
    '',
  );

  return [
    '<#',
    '.SYNOPSIS',
    'Load the varlock __VARLOCK_ENV blob into a typed object.',
    '',
    '.DESCRIPTION',
    'Reads the __VARLOCK_ENV environment variable set by `varlock run`, decrypts it if it is a varlock:v1 blob using _VARLOCK_ENV_KEY, and returns the typed object for this project.',
    '',
    'The object is a snapshot of the values at load time. Each property holds the value with the type shown below, and an optional item that is unset is $null. Composite values are JsonElement. Read a value from its property, or pipe the object to Select-Object. Call the command again to read values after the environment changes.',
    '',
    'If __VARLOCK_ENV is missing (the script wasn\'t started with varlock run), or a required key is absent, the command throws.',
    '',
    ...(properties.length ? ['Properties:', ...propertyLines, ''] : []),
    ...examples,
    '.INPUTS',
    'None. This command takes no pipeline input.',
    '',
    '.OUTPUTS',
    typeFullName,
    'An object with one property for each schema item (see Properties).',
    '',
    '.NOTES',
    'Requires PowerShell 7.4+ (.NET 8). The typed class is compiled with Add-Type the first time the file is loaded in a session.',
    'This file is generated by varlock. Regenerate it with varlock codegen instead of editing it by hand.',
    '',
    '.LINK',
    PWSH_DOCS_URL,
    '#>',
  ].map((line, i, all) => (i === 0 || i === all.length - 1 ? line : safeLine(line)));
}

export function generatePwshEnvSrc(
  fields: Array<ResolvedFieldType>,
  opts?: { functionName?: unknown },
): string {
  const functionName = opts?.functionName === undefined ? 'Get-Env' : String(opts.functionName);
  if (!PWSH_FUNCTION_NAME.test(functionName)) {
    throw new Error(`@generatePwshEnv - \`function\` must be a Verb-Noun PowerShell function name (got ${JSON.stringify(opts?.functionName)})`);
  }

  // the namespace hashes the generated C#, so a changed schema compiles to a new type
  const probe = generateCsharpEnvSrc(fields, { namespace: 'Varlock.Pwsh', className: 'Env' });
  const typeId = createHash('sha256').update(probe).digest('hex').slice(0, 12);
  const namespace = `Varlock.Pwsh_${typeId}`;
  const fullName = `${namespace}.Env`;
  const csharpSrc = generateCsharpEnvSrc(fields, { namespace, className: 'Env' });

  // the properties are the ones the C# class declares, so the help matches the object
  const csharpTypes = csharpPropertyTypes(csharpSrc);
  const properties = fields
    .map((field) => ({ field, prop: snakeToPascalCase(field.key) }))
    .filter(({ prop }) => csharpTypes.has(prop))
    .map(({ field, prop }) => ({ field, prop, type: psTypeName(csharpTypes.get(prop) ?? 'object') }));
  const sensitiveList = getSensitiveKeys(fields).map(pwshStringLiteral).join(', ');

  const src = [
    getAutogeneratedBanner('#'),
    '# Requires PowerShell 7.4+ (.NET 8). The C# source uses System.Text.Json and AesGcm, compiled with Add-Type.',
    '',
    'if ($PSVersionTable.PSVersion -lt [version]\'7.4\') {',
    '    throw \'varlock: this generated module requires PowerShell 7.4 or later\'',
    '}',
    '',
    `if (-not (${pwshStringLiteral(fullName)} -as [type])) {`,
    // `#nullable enable` is needed for the `string?` members, and the define selects the
    // AesGcm constructor that takes a tag size (the other one is obsolete on .NET 8)
    '    Add-Type -CompilerOptions \'/define:NET8_0_OR_GREATER\' -TypeDefinition @\'',
    '#nullable enable',
    ...csharpSrc.split('\n'),
    '\'@',
    '}',
    '',
    `function ${functionName}SensitiveKeys {`,
    `    @(${sensitiveList})`,
    '}',
    '',
    ...helpLines(functionName, fullName, properties),
    `function ${functionName} {`,
    '    [CmdletBinding()]',
    `    [OutputType(${pwshStringLiteral(fullName)})]`,
    '    param()',
    '',
    `    [${fullName}]::Load()`,
    '}',
    '',
  ];

  return src.join('\n');
}
